/**
 * 知时 · 标签体系（单一事实来源）
 * ============================
 *
 * 为什么要有这个文件：
 *   采集器最初用的是「粗标签」（讲座活动 / 学工事务 / 校内通知 …），
 *   订阅侧用的是「细标签」（转专业 / 学科竞赛 / 奖助学金 …）。
 *   两套词表对不上，就会出现「我订了学科竞赛，但通知被标成校内通知，推不过来」。
 *
 *   所以这里做两件事：
 *     ① 定一份**统一的标签词表**（TAGS），订阅、推送、搜索、展示都用它
 *     ② 给一个**标题关键词 → 标签**的归类函数（classify），把历史通知重新归档
 *
 * 注意：这只是「本地归类」，属于规则层面的粗匹配。
 *   云服务开通后，归类交给理解层（大模型读全文判定），本文件退化为兜底策略。
 *   接口保持不变，上层无需改动。
 */

