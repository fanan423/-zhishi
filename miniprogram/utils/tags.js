/**
 * 归类：只根据标题（标题最准），标题判不出再看正文前 200 字
 * @returns 标签 key
 */
function classify(title, body) {
  const t = String(title || '');
  const b = String(body || '').slice(0, 200);

  for (const r of RULES) {
    for (const k of r.kw) {
      if (t.indexOf(k) >= 0) return r.tag;
    }
  }
  for (const r of RULES) {
    for (const k of r.kw) {
      if (b.indexOf(k) >= 0) return r.tag;
    }
  }
  return '校内通知';
}

/* 判断一个标签是否属于「用户可选关注项」（校内通知 = 兜底，默认不清空） */
function isSubscribable(key) {
  return TAG_KEYS.indexOf(key) >= 0;
}

module.exports = { TAGS, TAG_KEYS, meta, classify, isSubscribable };
