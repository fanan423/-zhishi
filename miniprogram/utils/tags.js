const TAG_KEYS = TAGS.map(t => t.key);

/* 标签元信息查询 */
function meta(key) {
  return TAGS.find(t => t.key === key) || { key: key || '校内通知', icon: '📢', desc: '', color: 'gray' };
}

/* ============ 标题/正文关键词 → 标签 ============ */
